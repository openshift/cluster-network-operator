// stderr logs CLI diagnostics
var stderr = log.New(os.Stderr, "", 0)

const (
	suiteSerial     = "cluster-network-operator/conformance/serial"
	suiteParallel   = "cluster-network-operator/conformance/parallel"
	suiteDisruptive = "cluster-network-operator/conformance/disruptive"
)

// Run generates AppendedAnnotations for discovered Ginkgo specs into the path
// given as os.Args[1] (same flow as ovn-kubernetes openshift/test/annotate).
func Run(labelToTestName, labelToLabel map[string][]string, filter func(name string) bool) {
	if len(os.Args) != 2 {
		fmt.Fprintf(os.Stderr, "error: requires exactly one argument which is a path to the output file\n")
		os.Exit(1)
	}
	if err := ginkgo.GetSuite().BuildTree(); err != nil {
		fmt.Fprintf(os.Stderr, "error: failed to build ginkgo suite test tree: %v\n", err)
		os.Exit(1)
	}
	generator := newGenerator(labelToTestName, labelToLabel)
	ginkgo.GetSuite().WalkTests(generator.generate)
	if len(generator.errors) > 0 {
		for _, s := range generator.errors {
			fmt.Fprintf(os.Stderr, "appending label failed: %s\n", s)
		}
		os.Exit(1)
	}
	ginkgo.GetSuite().WalkTests(generator.appendLabelsToTestName)
	if len(generator.missing) > 0 {
		var names []string
		for name := range generator.missing {
			names = append(names, name)
		}
		sort.Strings(names)
		fmt.Fprintf(os.Stderr, "appending label failed:\n%s\n", strings.Join(names, "\n"))
		os.Exit(1)
	}

	var pairs []string
	for testName, labels := range generator.output {
		if filter(fmt.Sprintf("%s%s", testName, labels)) {
			continue
		}
		pairs = append(pairs, fmt.Sprintf("%q:\n%q,", testName, labels))
	}
	sort.Strings(pairs)
	contents := fmt.Sprintf(`package generated

import (
	"fmt"

	"github.com/onsi/ginkgo/v2"
	"github.com/onsi/ginkgo/v2/types"
)

// AppendedAnnotations maps the original Ginkgo test name to brackets appended
// onto that name (e.g. [Serial][Suite:...]). Generated by cmd/annotate; do not
// edit by hand — run: make -C openshift-tests-ext update-annotations
var AppendedAnnotations = map[string]string{
%s
}

func init() {
	ginkgo.GetSuite().SetAnnotateFn(func(name string, node types.TestSpec) {
		if newLabels, ok := AppendedAnnotations[name]; ok {
			node.AppendText(newLabels)
		} else {
			panic(fmt.Sprintf("unable to find test %%s", name))
		}
	})
}
`, strings.Join(pairs, "\n\n"))
	outPath := filepath.Clean(os.Args[1])
	if outPath == "." || !strings.HasSuffix(outPath, ".go") {
		stderr.Printf("error: output path must be a .go file, got %q", os.Args[1])
		os.Exit(1)
	}
	// Generated source is committed to the repo; keep conventional 0644 mode.
	if err := os.WriteFile(outPath, []byte(contents), 0o644); err != nil { //nolint:gosec // G306: generated Go source file
		stderr.Printf("error: failed to write generated annotations file at path %q: %v", outPath, err)
		os.Exit(1)
	}
	// Fixed argv to gofmt; outPath is validated above as a .go file path.
	if _, err := exec.CommandContext(context.Background(), "gofmt", "-s", "-w", outPath).Output(); err != nil { //nolint:gosec // G702: gofmt with validated path
		stderr.Printf("error: failed to format golang file at path %q: %v", outPath, err)
		os.Exit(1)
	}
}

type labelAppender struct {
	labels              []string
	stringMatches       map[string][]string
	matches             map[string]*regexp.Regexp
	excludedTestsFilter *regexp.Regexp
	labelToLabel        map[string][]string
	output              map[string]string
	missing             map[string]struct{}
	errors              []string
}

func newGenerator(labelToTestNames, labelToLabels map[string][]string) *labelAppender {
	allLabelsSet := sets.New[string]()
	matches := make(map[string]*regexp.Regexp)
	stringMatches := make(map[string][]string)
	for _, labels := range labelToLabels {
		allLabelsSet.Insert(labels...)
	}

	for label, matchTestNames := range labelToTestNames {
		sort.Strings(matchTestNames)
		allLabelsSet.Insert(label)
		var remain []string
		for _, matchTestName := range matchTestNames {
			re := regexp.MustCompile(matchTestName)
			if p, ok := re.LiteralPrefix(); ok {
				stringMatches[label] = append(stringMatches[label], p)
			} else {
				remain = append(remain, matchTestName)
			}
		}
		if len(remain) > 0 {
			matches[label] = regexp.MustCompile(strings.Join(remain, `|`))
		}
	}

	excludedTestsFilter := regexp.MustCompile(strings.Join(ExcludedTests, `|`))

	return &labelAppender{
		labels:              sets.List(allLabelsSet),
		stringMatches:       stringMatches,
		matches:             matches,
		labelToLabel:        labelToLabels,
		excludedTestsFilter: excludedTestsFilter,
		output:              make(map[string]string),
		missing:             make(map[string]struct{}),
	}
}

func (r *labelAppender) appendLabelsToTestName(name string, node types.TestSpec) {
	if newLabels, ok := r.output[name]; ok {
		node.AppendText(newLabels)
	} else {
		r.missing[name] = struct{}{}
	}
}

func (r *labelAppender) generate(name string, node types.TestSpec) {
	var labelsB, nameB strings.Builder
	nameB.WriteString(name)

	for {
		count := 0
		newName := nameB.String()
		for _, label := range r.labels {
			if strings.Contains(newName, label) {
				continue
			}
			var isLabelRequired bool
			for _, segment := range r.stringMatches[label] {
				isLabelRequired = strings.Contains(newName, segment)
				if isLabelRequired {
					break
				}
			}
			if !isLabelRequired {
				if re := r.matches[label]; re != nil {
					isLabelRequired = re.MatchString(newName)
				}
			}
			if !isLabelRequired {
				if potentialLabels, ok := r.labelToLabel[label]; ok {
					for _, potentialLabel := range potentialLabels {
						isLabelRequired = containsLabel(node.Labels(), potentialLabel)
						if isLabelRequired {
							break
						}
					}
				}
			}

			if isLabelRequired {
				count++
				labelsB.WriteString(label)
				nameB.WriteString(label)
				newName = nameB.String()
			}
		}
		if count == 0 {
			break
		}
	}

	newName := nameB.String()
	if !r.excludedTestsFilter.MatchString(newName) && !strings.Contains(newName, "[Suite:") {
		isSerial := strings.Contains(newName, "[Serial]") || containsLabel(node.Labels(), "Serial")
		isDisruptive := containsLabel(node.Labels(), "Disruptive")
		switch {
		case isDisruptive:
			labelsB.WriteString("[Suite:" + suiteDisruptive + "]")
		case isSerial:
			labelsB.WriteString("[Suite:" + suiteSerial + "]")
		default:
			labelsB.WriteString("[Suite:" + suiteParallel + "]")
		}
	}

	newLabels := labelsB.String()
	if err := checkBalancedBrackets(newName + newLabels); err != nil {
		r.errors = append(r.errors, err.Error())
	}

	r.output[name] = newLabels
}

func checkBalancedBrackets(testName string) error {
	stack := make([]int, 0, len(testName))
	for idx, c := range testName {
		switch c {
		case '[':
			stack = append(stack, idx)
		case ']':
			if len(stack) == 0 {
				stack = append(stack, idx)
			} else {
				stack = stack[:len(stack)-1]
			}
		}
	}

	if len(stack) > 0 {
		var b strings.Builder
		b.Grow(len(testName)*2 + 1)
		b.WriteString(testName)
		b.WriteByte('\n')
	outerLoop:
		for i := range len(testName) {
			for _, loc := range stack {
				if i == loc {
					b.WriteByte('^')
					continue outerLoop
				}
			}
			b.WriteByte(' ')
		}
		return fmt.Errorf("unbalanced brackets in test name:\n%s", b.String())
	}
	return nil
}

func containsLabel(labels []string, candidateLabel string) bool {
	for _, label := range labels {
		if stripBrackets(label) == stripBrackets(candidateLabel) {
			return true
		}
	}
	return false
}

func stripBrackets(s string) string {
	return strings.TrimFunc(s, func(r rune) bool {
		return r == '[' || r == ']'
	})
}
